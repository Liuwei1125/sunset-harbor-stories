"""Bake original outdoor lighting: GGX-filtered radiance + cosine diffuse.

Run with Blender's Python (bundled NumPy):
blender --background --python tools/build_lighting.py
Produces a synchronous RGBM atlas for the offline game, and an HDR for Blender.
"""
from pathlib import Path
import base64
import hashlib
import json
import math
import importlib.util
import os
import shutil
import subprocess
import sys

if importlib.util.find_spec('numpy') is None:
    executable=os.environ.get('BLENDER') or shutil.which('blender') or '/Applications/Blender.app/Contents/MacOS/Blender'
    if not Path(executable).is_file():
        raise SystemExit('Lighting bake needs NumPy or Blender. Set BLENDER to the Blender executable.')
    raise SystemExit(subprocess.run([executable,'--background','--python',str(Path(__file__).resolve())]).returncode)
import numpy as np

ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'assets'/'lighting';OUT.mkdir(parents=True,exist_ok=True)
W,H=256,128
SUN=np.array([-.65,.95,.45]);SUN/=np.linalg.norm(SUN)

def normalize(a):return a/np.maximum(np.linalg.norm(a,axis=-1,keepdims=True),1e-9)
def sky(r):
    y=r[...,1:2];up=np.clip(y,0,1)
    # Clear coastal daylight. The old nearly white horizon overwhelmed material
    # color; warm ground bounce now carries the fill without bleaching the sky.
    horizon=np.array([.20,.40,.76]);zenith=np.array([.025,.14,.47])
    c=horizon+(zenith-horizon)*np.power(up,.42)
    warm=np.power(np.clip(np.sum(r*SUN,axis=-1,keepdims=True),0,1),12)*np.power(1-up,.6)
    c+=warm*np.array([.27,.13,.035])
    # Broad original cloud bands, baked identically into diffuse and reflections.
    clouds=np.clip((np.sin(r[...,0:1]*17+r[...,2:3]*8)+.5*np.sin(r[...,2:3]*34-r[...,0:1]*11)-.15)*.9,0,1)
    clouds*=np.clip((y-.12)*2.5,0,1)*np.clip((.95-y)*2,0,1)
    c=c*(1-clouds*.24)+np.array([.78,.84,.91])*clouds*.24
    ground=np.array([.36,.30,.22])+.07*np.power(np.clip(1+y,0,1),3)
    return np.where(y>=0,c,ground).astype(np.float32)

u,v=np.meshgrid((np.arange(W)+.5)/W,(np.arange(H)+.5)/H)
theta=(u-.5)*2*np.pi;phi=v*np.pi
N=np.stack([np.sin(phi)*np.cos(theta),np.cos(phi),np.sin(phi)*np.sin(theta)],-1).reshape(-1,3).astype(np.float32)
axis=np.tile(np.array([0,1,0],np.float32),(len(N),1));axis[np.abs(N[:,1])>.98]=[1,0,0]
T=normalize(np.cross(axis,N));B=np.cross(N,T)
levels=[sky(N).reshape(H,W,3)]
SAMPLES=96
def radical(i):
    out=0.;power=.5
    while i:out+=(i&1)*power;power*=.5;i>>=1
    return out
for level in range(1,6):
    rough=level/5;alpha=rough*rough;total=np.zeros_like(N);weight=np.zeros((len(N),1),np.float32)
    for sample in range(SAMPLES):
        xi=(sample+.5)/SAMPLES;angle=2*np.pi*radical(sample)
        cost=np.sqrt((1-xi)/(1+(alpha*alpha-1)*xi));sint=np.sqrt(1-cost*cost)
        half=T*(sint*np.cos(angle))+B*(sint*np.sin(angle))+N*cost
        L=normalize(2*np.sum(N*half,axis=-1,keepdims=True)*half-N)
        ndl=np.maximum(0,np.sum(N*L,axis=-1,keepdims=True));total+=sky(L)*ndl;weight+=ndl
    levels.append((total/np.maximum(weight,1e-6)).reshape(H,W,3))
    print('GGX level',level,flush=True)
diffuse=np.zeros_like(N)
for sample in range(128):
    xi=(sample+.5)/128;angle=2*np.pi*radical(sample)
    L=T*(np.sqrt(xi)*np.cos(angle))+B*(np.sqrt(xi)*np.sin(angle))+N*np.sqrt(1-xi)
    diffuse+=sky(L)/128
levels.append(diffuse.reshape(H,W,3));levels.append(levels[0])
atlas=np.concatenate(levels,axis=0);m=np.clip(np.ceil(np.max(atlas,axis=-1,keepdims=True)/8*255)/255,1/255,1)
rgb=np.clip(atlas/(m*8)*255,0,255).astype(np.uint8);rgba=np.concatenate([rgb,np.round(m*255).astype(np.uint8)],-1)
data=rgba.tobytes()
pack={'width':W,'height':H*8,'tileHeight':H,'levels':6,'range':8,'sun':SUN.tolist(),'rgbm':base64.b64encode(data).decode()}
(OUT/'lighting-pack.js').write_text('// Original Harbor Radiance / generated by tools/build_lighting.py\nconst LIGHTING_PACK9='+json.dumps(pack,separators=(',',':'))+';\n')
# Standard RGBE HDR: exact same environment for offline Blender reference renders.
raw=bytearray(f'#?RADIANCE\nFORMAT=32-bit_rle_rgbe\n\n-Y {H} +X {W}\n'.encode())
for row in levels[0]:
    peak=np.max(row,axis=-1);mantissa,exponent=np.frexp(peak);scale=mantissa*256/np.maximum(peak,1e-9)
    rgbe=np.concatenate([(row*scale[:,None]).astype(np.uint8),(exponent+128).astype(np.uint8)[:,None]],-1)
    raw.extend((2,2,W>>8,W&255))
    for channel in rgbe.T:
        for offset in range(0,W,128):part=channel[offset:offset+128].tobytes();raw.append(len(part));raw.extend(part)
(OUT/'harbor-environment.hdr').write_bytes(raw)
(OUT/'manifest.json').write_text(json.dumps({'generator':'tools/build_lighting.py','source':'Original analytical outdoor radiance, no stock photograph','sampling':'96 GGX importance samples per specular texel, 128 cosine hemisphere samples per diffuse texel','atlas':[W,H*8],'sun':SUN.tolist(),'files':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in OUT.iterdir() if p.suffix in ['.hdr','.js']}},indent=2)+'\n')
print('Wrote lighting pack:',len(data),'decoded bytes',flush=True)
